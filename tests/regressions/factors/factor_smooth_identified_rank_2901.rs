#[test]
fn factor_smooth_fit_certifies_its_identified_rank_2901() {
    init_parallelism();
    let headers = vec!["x".to_string(), "g".to_string(), "y".to_string()];
    let records: Vec<StringRecord> = ROWS
        .lines()
        .map(|line| StringRecord::from(line.split(',').collect::<Vec<&str>>()))
        .collect();
    assert_eq!(records.len(), 120, "the seed-0 fixture has 120 rows");
    let dataset =
        encode_recordswith_inferred_schema(headers, records).expect("encode the fs fixture");
    let outcome = fit_from_formula(
        "y ~ s(x) + s(x, g, bs='fs')",
        &dataset,
        &FitConfig::default(),
    );
    assert!(
        outcome.is_ok(),
        "the factor-smooth fit must certify its identified rank: {}",
        outcome
            .as_ref()
            .err()
            .map(ToString::to_string)
            .unwrap_or_default()
    );
}
